#!/usr/bin/env python3
"""
Builds a "quicklook" YOLO-format dataset (images + .txt labels) from:
    - the world's texture atlases (pv_atlas_NN_albedo.png)
    - defects.json (position and type of each defect, generated by the
      world)

This is the fast, camera-free path: each module (atlas cell) is cropped
as-is into a standalone "head-on" image, without going through any Gazebo
render or camera model -- hence "quicklook". For the dataset meant for the
real detector, with shots from the drone's own camera and boxes projected
in 3D, use `tools/capture_dataset/capture_dataset.py` instead (see
`tools/README.md`).

If the module is damaged, a YOLO label file is also generated with the
class and bounding box of each defect, normalised to the module crop. If
it's clean, an empty label is generated (background image, no objects) --
useful so the model also learns what a healthy panel looks like.

USAGE (from anywhere, doesn't depend on the working directory):
    # 1. First, inspect defects.json's actual structure
    #    (needed once, to confirm the field names):
    python3 tools/build_quicklook_dataset.py --inspect

    # 2. If the bounding box extracts correctly, build the full dataset:
    python3 tools/build_quicklook_dataset.py

Output (in OUTPUT_DIR, quicklook_dataset/ at the project root by default):
    images/<atlas>_<module>.png
    labels/<atlas>_<module>.txt      (YOLO format: class xc yc w h, normalised 0-1)
    classes.txt                      (one class per line, in ID order)
"""

import argparse
import json
import os

from PIL import Image, ImageDraw

# ---------------------------------------------------------------------
# CONFIGURATION -- adjust the paths to your environment
# ---------------------------------------------------------------------

PROJECT_ROOT = os.path.expanduser("~/solar_farm_sim")
WORLD_DIR = os.path.join(PROJECT_ROOT, "src", "solar_farm_gz", "worlds")
TEXTURES_DIR = os.path.join(WORLD_DIR, "solar_farm_assets/materials/textures")
DEFECTS_JSON_PATH = os.path.join(WORLD_DIR, "defects.json")

OUTPUT_DIR = os.path.join(PROJECT_ROOT, "quicklook_dataset")

# Classes, in the order their ID (0, 1, 2, 3...) will be assigned -- must
# match the "type" values that appear in defects.json.
CLASSES = ["dirt", "bird_dropping", "crack", "delamination"]

# Atlas geometry (see docs/METHODOLOGY.md): 5x2 grid of cells, 512x1024 px
# each, 2560x2048 total atlas.
ATLAS_COLS = 5
ATLAS_ROWS = 2
CELL_W = 512
CELL_H = 1024

# If the UV coordinates have their origin at the bottom (the usual
# convention for 3D mesh UVs) instead of the top (image convention), the Y
# axis needs flipping when converting to YOLO format. Starts as False;
# flip it to True if visual verification (--verify) shows the boxes sitting
# "upside down" relative to the actual defect.
FLIP_V = False


# ---------------------------------------------------------------------
# Step 1 -- inspect defects.json's actual structure
# ---------------------------------------------------------------------

def inspect(defects):
    """Prints the first damaged module it finds, exactly as it is in the
    JSON, so the bounding-box field names can be confirmed before trying
    to extract them automatically."""
    for atlas_name, modules in defects["atlases"].items():
        for m in modules:
            if not m["clean"]:
                print(f"Example damaged module (atlas={atlas_name}):\n")
                print(json.dumps(m, indent=2, ensure_ascii=False))
                return
    print("No damaged module found in defects.json.")


# ---------------------------------------------------------------------
# Step 2 -- bounding box extraction
# ---------------------------------------------------------------------

def extract_bbox_yolo(defect):
    """Returns (xc, yc, w, h) already normalised 0-1 relative to the
    module, ready for YOLO format. The world already exports this
    directly in 'bbox_uv_cxcywh' (the module's own UV coordinates), so no
    pixel conversion is needed."""
    if "bbox_uv_cxcywh" in defect:
        xc, yc, w, h = defect["bbox_uv_cxcywh"]
        if FLIP_V:
            yc = 1.0 - yc
        return xc, yc, w, h

    raise ValueError(
        "'bbox_uv_cxcywh' not found on this defect. Run --inspect and "
        "check the actual field name.\n"
        f"Defect content: {json.dumps(defect, ensure_ascii=False)}"
    )


def cell_origin(module):
    """Uses 'atlas_cell' [col, row] if present (more reliable); otherwise
    computes it from module_index as a fallback."""
    if "atlas_cell" in module:
        col, row = module["atlas_cell"]
    else:
        idx = module["module_index"]
        col, row = idx % ATLAS_COLS, idx // ATLAS_COLS
    return col * CELL_W, row * CELL_H


# ---------------------------------------------------------------------
# Step 3 -- visual verification (draws the boxes over a few examples)
# ---------------------------------------------------------------------

def verify(defects, n_samples=6):
    verify_dir = os.path.join(OUTPUT_DIR, "verify")
    os.makedirs(verify_dir, exist_ok=True)
    shown = 0

    for atlas_name, modules in defects["atlases"].items():
        albedo_path = os.path.join(TEXTURES_DIR, f"{atlas_name}_albedo.png")
        if not os.path.exists(albedo_path):
            continue
        atlas_img = Image.open(albedo_path).convert("RGB")

        for m in modules:
            if m["clean"] or shown >= n_samples:
                continue
            ox, oy = cell_origin(m)
            crop = atlas_img.crop((ox, oy, ox + CELL_W, oy + CELL_H)).copy()
            draw = ImageDraw.Draw(crop)

            for defect in m["defects"]:
                xc, yc, w, h = extract_bbox_yolo(defect)
                x_min = (xc - w / 2) * CELL_W
                y_min = (yc - h / 2) * CELL_H
                x_max = (xc + w / 2) * CELL_W
                y_max = (yc + h / 2) * CELL_H
                draw.rectangle([x_min, y_min, x_max, y_max], outline="red", width=4)
                draw.text((x_min + 4, y_min + 4), defect["type"], fill="red")

            base_name = f"{atlas_name}_{m['module_index']:02d}"
            crop.save(os.path.join(verify_dir, base_name + "_verify.png"))
            shown += 1
        if shown >= n_samples:
            break

    print(f"Saved {shown} verification images to: {verify_dir}")
    print("Open them and check that the red box lands on the actual defect.")
    print("If the boxes appear vertically flipped (e.g. the stain is at the")
    print("top but the box appears at the bottom), set FLIP_V = True at the")
    print("top of the script and re-run --verify.")


# ---------------------------------------------------------------------
# Step 4 -- build the full dataset
# ---------------------------------------------------------------------

def build_dataset(defects):
    images_dir = os.path.join(OUTPUT_DIR, "images")
    labels_dir = os.path.join(OUTPUT_DIR, "labels")
    os.makedirs(images_dir, exist_ok=True)
    os.makedirs(labels_dir, exist_ok=True)

    # classes.txt, in the same order as CLASSES (their IDs are their index)
    with open(os.path.join(OUTPUT_DIR, "classes.txt"), "w") as f:
        f.write("\n".join(CLASSES) + "\n")

    n_clean, n_damaged, n_defects, n_errors = 0, 0, 0, 0

    for atlas_name, modules in defects["atlases"].items():
        albedo_path = os.path.join(TEXTURES_DIR, f"{atlas_name}_albedo.png")
        if not os.path.exists(albedo_path):
            print(f"  warning: can't find {albedo_path}, skipping this atlas")
            continue
        atlas_img = Image.open(albedo_path).convert("RGB")

        for m in modules:
            ox, oy = cell_origin(m)
            idx = m["module_index"]

            # Crop the module out of the atlas
            crop = atlas_img.crop((ox, oy, ox + CELL_W, oy + CELL_H))
            base_name = f"{atlas_name}_{idx:02d}"
            crop.save(os.path.join(images_dir, base_name + ".png"))

            label_path = os.path.join(labels_dir, base_name + ".txt")

            if m["clean"]:
                # Background image: empty label (no objects)
                open(label_path, "w").close()
                n_clean += 1
                continue

            n_damaged += 1
            lines = []
            for defect in m["defects"]:
                cls_name = defect["type"]
                if cls_name not in CLASSES:
                    print(f"  warning: unknown class '{cls_name}' in {base_name}, skipped")
                    continue
                cls_id = CLASSES.index(cls_name)
                try:
                    xc, yc, w, h = extract_bbox_yolo(defect)
                except ValueError as e:
                    print(f"  error in {base_name}: {e}")
                    n_errors += 1
                    continue

                lines.append(f"{cls_id} {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}")
                n_defects += 1

            with open(label_path, "w") as f:
                f.write("\n".join(lines) + ("\n" if lines else ""))

    print("\nSummary:")
    print(f"  clean modules (background):  {n_clean}")
    print(f"  damaged modules:             {n_damaged}")
    print(f"  labelled defects:            {n_defects}")
    print(f"  bounding-box errors:         {n_errors}")
    print(f"\nDataset generated in: {OUTPUT_DIR}")
    print("  -> images/   (crop of each module)")
    print("  -> labels/   (YOLO labels, one .txt per image)")
    print("  -> classes.txt")
    if n_errors:
        print("\n⚠ There were errors extracting bounding boxes -- check the "
              "messages above before using the dataset.")


# ---------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--inspect", action="store_true",
                         help="Only show the structure of one example defect, without generating anything")
    parser.add_argument("--verify", action="store_true",
                         help="Generate a few images with the boxes drawn, to eyeball them")
    args = parser.parse_args()

    with open(DEFECTS_JSON_PATH) as f:
        defects = json.load(f)

    if args.inspect:
        inspect(defects)
    elif args.verify:
        verify(defects)
    else:
        build_dataset(defects)


if __name__ == "__main__":
    main()
